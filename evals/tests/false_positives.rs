//! The false-positive rate, measured on the legitimate-transfer corpus.
//!
//! This is the eval that is supposed to make us uncomfortable. Airlock holds
//! genuine first-time transfers — that is inherent to judging novelty, not a
//! bug to tune away — and the brief's answer is to measure it, report it, and
//! mitigate it with a one-tap release rather than hide it.
//!
//! So a legitimate case that holds is **not** a test failure. The test
//! failure is the rate drifting past what we have agreed to stand behind, or
//! the number in the README going stale.
//!
//! Running this rewrites `evals/measured.md`, so the figure we quote is
//! regenerated rather than remembered.

use airlock_evals::{held, load, run_case, Expect};
use std::fmt::Write as _;

/// The rate we are willing to defend out loud. Raising this is a decision to
/// take to the team, not a number to nudge until the test passes.
const CEILING: f64 = 0.20;

#[tokio::test]
async fn the_false_positive_rate_is_measured_and_written_down() {
    let cases = load("legitimate.json");
    assert!(!cases.is_empty(), "corpus is empty");

    let mut rows = Vec::new();
    let mut false_positives = 0usize;
    for case in &cases {
        assert_eq!(case.expect, Expect::Pass, "{} is in the legitimate corpus", case.name);
        let did_hold = held(&run_case(case).await);
        if did_hold {
            false_positives += 1;
        }
        rows.push((case.name.clone(), case.established, did_hold));
    }

    let rate = false_positives as f64 / cases.len() as f64;

    let mut report = String::new();
    writeln!(report, "# Measured false-positive rate\n").unwrap();
    writeln!(
        report,
        "Regenerated by `cargo test -p airlock-evals`. Do not edit by hand.\n"
    )
    .unwrap();
    writeln!(
        report,
        "**{false_positives} of {} legitimate transfers were held — {:.0}%.**\n",
        cases.len(),
        rate * 100.0
    )
    .unwrap();
    writeln!(report, "| Case | Established recipient | Outcome |").unwrap();
    writeln!(report, "|---|---|---|").unwrap();
    for (name, established, did_hold) in &rows {
        writeln!(
            report,
            "| {name} | {} | {} |",
            if *established { "yes" } else { "no" },
            if *did_hold { "**held**" } else { "passed" }
        )
        .unwrap();
    }
    writeln!(
        report,
        "\nEvery held transfer above is releasable by the account holder in one tap \
         once the cooling period elapses. The cost of a false positive is a minute; \
         the cost of a false negative is the wallet."
    )
    .unwrap();
    writeln!(
        report,
        "\n**Read this figure carefully.** It is {} hand-written cases against the stub \
         Reader, not production traffic — the sample is far too small to quote as a \
         real-world rate, and the corpus was written by the same people who wrote the \
         rules it grades. It is a regression guard and an honest starting point, not \
         a benchmark result.",
        cases.len()
    )
    .unwrap();

    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("measured.md");
    std::fs::write(&path, &report).expect("could not write measured.md");

    println!("\n{report}");

    assert!(
        rate <= CEILING,
        "false-positive rate {:.0}% exceeds the {:.0}% we agreed to stand behind",
        rate * 100.0,
        CEILING * 100.0
    );
}

/// Rule 1 is the main thing keeping the rate survivable: ordinary traffic
/// goes to people you have paid before. If an established recipient ever
/// holds, the rate is about to become indefensible.
#[tokio::test]
async fn an_established_recipient_is_never_held() {
    for case in load("legitimate.json").iter().filter(|c| c.established) {
        assert!(
            !held(&run_case(case).await),
            "{} held despite an established recipient",
            case.name
        );
    }
}
